/**
 * Copies the few Lucide icons the film uses out of the app's generated icon table
 * (src/lib/icons.generated.ts, read only) into src/lib/icons.data.ts, as plain SVG path data
 * on Lucide's 24-unit grid. Rects, circles and lines become paths, so every icon is one
 * stroked path the film can scale, tint and draw on.
 *
 *   npm run icons
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const APP_ICONS = path.resolve(HERE, "../../src/lib/icons.generated.ts");
const OUT = path.resolve(HERE, "../src/lib/icons.data.ts");

const WANTED = [
	"laptop", "utensils", "footprints", "mail", "languages", "phone", "dumbbell", "book-open",
	"bell", "bell-ring", "alarm", "trash", "rotate", "undo", "lock", "shield", "cpu", "sun", "moon",
	"sunrise", "sunset", "sparkle", "sparkles", "check", "calendar", "video", "users", "coffee",
	"bot", "settings", "kanban", "chart-gantt", "earth", "globe", "focus", "palette", "monitor",
	"brain", "pill", "timer", "hourglass", "leaf", "plus", "sliders", "map-pin", "columns", "mihrab", "calendar-days",
];

type IconNode = [string, Record<string, string | number>];

function readTable(): Record<string, IconNode[]> {
	const src = fs.readFileSync(APP_ICONS, "utf8");
	const start = src.indexOf("{", src.indexOf("ICON_NODES"));
	let depth = 0;
	let end = start;
	for (; end < src.length; end++) {
		if (src[end] === "{") depth++;
		else if (src[end] === "}" && --depth === 0) break;
	}
	return JSON.parse(src.slice(start, end + 1));
}

const n = (v: string | number | undefined, d = 0) => (v === undefined ? d : Number(v));

function toPath([tag, a]: IconNode): string {
	switch (tag) {
		case "path": {
			// A path's first "m" is from the origin; joined to the others it must still be.
			const d = String(a.d).trim();
			return d.startsWith("m") ? `M0 0${d}` : d;
		}
		case "circle": {
			const cx = n(a.cx), cy = n(a.cy), r = n(a.r);
			return `M${cx - r} ${cy}A${r} ${r} 0 1 0 ${cx + r} ${cy}A${r} ${r} 0 1 0 ${cx - r} ${cy}Z`;
		}
		case "ellipse": {
			const cx = n(a.cx), cy = n(a.cy), rx = n(a.rx), ry = n(a.ry);
			return `M${cx - rx} ${cy}A${rx} ${ry} 0 1 0 ${cx + rx} ${cy}A${rx} ${ry} 0 1 0 ${cx - rx} ${cy}Z`;
		}
		case "line":
			return `M${n(a.x1)} ${n(a.y1)}L${n(a.x2)} ${n(a.y2)}`;
		case "rect": {
			const x = n(a.x), y = n(a.y), w = n(a.width), h = n(a.height);
			const r = Math.min(n(a.rx, n(a.ry)), w / 2, h / 2);
			if (r <= 0) return `M${x} ${y}H${x + w}V${y + h}H${x}Z`;
			return `M${x + r} ${y}H${x + w - r}A${r} ${r} 0 0 1 ${x + w} ${y + r}V${y + h - r}A${r} ${r} 0 0 1 ${x + w - r} ${y + h}H${x + r}A${r} ${r} 0 0 1 ${x} ${y + h - r}V${y + r}A${r} ${r} 0 0 1 ${x + r} ${y}Z`;
		}
		case "polyline":
		case "polygon": {
			const pts = String(a.points).trim().split(/[\s,]+/).map(Number);
			let d = `M${pts[0]} ${pts[1]}`;
			for (let i = 2; i < pts.length; i += 2) d += `L${pts[i]} ${pts[i + 1]}`;
			return tag === "polygon" ? `${d}Z` : d;
		}
		default:
			throw new Error(`icon element <${tag}> is not handled`);
	}
}

const table = readTable();
const out: Record<string, string> = {};
for (const name of WANTED) {
	const nodes = table[name];
	if (!nodes) throw new Error(`no icon named "${name}" in the app's icon table`);
	out[name] = nodes.map(toPath).join(" ");
}

fs.writeFileSync(
	OUT,
	`// Generated by scripts/gen-icons.ts from the app's Lucide icon table (ISC License, © Lucide Icons and Contributors).\n// Do not edit by hand: run \`npm run icons\`.\n\nexport const ICON_PATHS = ${JSON.stringify(out, null, "\t")} as const;\n\nexport type IconName = keyof typeof ICON_PATHS;\n`,
);
console.log(`wrote ${Object.keys(out).length} icons to ${path.relative(process.cwd(), OUT)}`);
